-- Узгодження схеми БД зі специфікацією вимог (SRS Лаба 2 та UX Лаба 3):
-- 1. Захист від brute-force та блокування за спробами входу (G3)
-- 2. Одноразові токени скидання пароля (G3)
-- 3. Запити на розблокування облікового запису (M6, M7)
-- 4. Типи благодійних закладів-одержувачів (M8, M12, C10)
-- 5. Індекси для вибірок замовлень менеджера та збереження gift_log при видаленні замовлень (M3, 7.2.2.6, 7.2.2.7)

-- 1. Захист від brute-force у таблиці користувачів (G3)
ALTER TABLE users
    ADD COLUMN failed_login_attempts INT NOT NULL DEFAULT 0,
    ADD COLUMN locked_until TIMESTAMPTZ;

-- 2. Таблиця одноразових токенів скидання пароля (G3)
CREATE TABLE password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token VARCHAR(255) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    used_at TIMESTAMPTZ
);

CREATE UNIQUE INDEX uk_password_reset_tokens_token ON password_reset_tokens (token);
CREATE INDEX idx_password_reset_tokens_user_id ON password_reset_tokens (user_id);
CREATE INDEX idx_password_reset_tokens_expires_at ON password_reset_tokens (expires_at);

-- 3. Таблиця запитів на розблокування облікового запису (M6, M7)
CREATE TABLE unblock_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason VARCHAR(1000),
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    manager_comment VARCHAR(1000),
    resolved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_unblock_requests_user_id ON unblock_requests (user_id);
CREATE INDEX idx_unblock_requests_resolved_by ON unblock_requests (resolved_by_user_id);
CREATE INDEX idx_unblock_requests_status ON unblock_requests (status);

-- 4. Типи закладів-одержувачів благодійних замовлень (M8, M12, C10)
ALTER TABLE institutions
    ADD COLUMN type VARCHAR(50) NOT NULL DEFAULT 'ORPHANAGE'
    CHECK (type IN ('ORPHANAGE', 'BOARDING_SCHOOL', 'LIBRARY'));

CREATE INDEX idx_institutions_type ON institutions (type);

-- 5. Індекси для специфічних вибірок Менеджера (M3)
-- Фільтр замовлень «Не оплачено понад 7 днів» (п. 7.2.2.6)
CREATE INDEX idx_orders_unpaid_awaiting ON orders (created_at) WHERE status = 'AWAITING_PAYMENT';

-- Фільтр замовлень «Архів» — поставлені або скасовані (п. 7.2.2.7)
CREATE INDEX idx_orders_archived ON orders (status_changed_at) WHERE status IN ('DELIVERED', 'CANCELLED');

-- Збереження журналу подарованих книг gift_log при повному видаленні архівного замовлення (п. 7.2.2.7, M8)
ALTER TABLE gift_log DROP CONSTRAINT uk_gift_log_order_book;
ALTER TABLE gift_log ALTER COLUMN order_id DROP NOT NULL;
ALTER TABLE gift_log DROP CONSTRAINT gift_log_order_id_fkey;
ALTER TABLE gift_log ADD CONSTRAINT fk_gift_log_orders FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL;
