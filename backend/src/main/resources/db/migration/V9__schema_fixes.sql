-- V9__schema_fixes.sql
-- Патч 1: Узгодження схеми БД (Пункти А.1, А.4, А.10)

-- 1. Захист від brute-force та блокування за спробами входу (G3)
ALTER TABLE users ADD COLUMN IF NOT EXISTS failed_login_attempts INT NOT NULL DEFAULT 0;
ALTER TABLE users ADD COLUMN IF NOT EXISTS locked_until TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS blocked_at TIMESTAMPTZ;
ALTER TABLE users ADD COLUMN IF NOT EXISTS block_reason TEXT;

-- 2. Одноразові токени скидання пароля (G3)
CREATE TABLE IF NOT EXISTS password_reset_tokens (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token VARCHAR(255) NOT NULL UNIQUE,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_user_id ON password_reset_tokens(user_id);
CREATE INDEX IF NOT EXISTS idx_password_reset_tokens_token ON password_reset_tokens(token);

-- 3. Запити на розблокування акаунтів (M6, M7)
CREATE TABLE IF NOT EXISTS unblock_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    reason TEXT NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'APPROVED', 'REJECTED')),
    manager_comment TEXT,
    resolved_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    resolved_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_unblock_requests_user_id ON unblock_requests(user_id);
CREATE INDEX IF NOT EXISTS idx_unblock_requests_status ON unblock_requests(status);
CREATE INDEX IF NOT EXISTS idx_unblock_requests_resolved_by ON unblock_requests(resolved_by_user_id);

-- 4. Типи благодійних закладів (M8, M12)
ALTER TABLE institutions ADD COLUMN IF NOT EXISTS type VARCHAR(50) NOT NULL DEFAULT 'ORPHANAGE';
ALTER TABLE institutions DROP CONSTRAINT IF EXISTS chk_institutions_type;
ALTER TABLE institutions ADD CONSTRAINT chk_institutions_type
    CHECK (type IN ('ORPHANAGE', 'BOARDING_SCHOOL', 'LIBRARY'));

-- 5. Зведення статусів замовлення до 4 значень (А.1): AWAITING_PAYMENT, PAID, DELIVERED, CANCELLED
-- Оновлення наявних рядків у orders та order_status_history
UPDATE orders SET status = 'PAID' WHERE status IN ('PROCESSING', 'ASSEMBLED', 'DELIVERING');
UPDATE order_status_history SET from_status = 'PAID' WHERE from_status IN ('PROCESSING', 'ASSEMBLED', 'DELIVERING');
UPDATE order_status_history SET to_status = 'PAID' WHERE to_status IN ('PROCESSING', 'ASSEMBLED', 'DELIVERING');

ALTER TABLE orders ALTER COLUMN status SET DEFAULT 'AWAITING_PAYMENT';

DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT constraint_name
        FROM information_schema.constraint_column_usage
        WHERE table_name = 'orders' AND column_name = 'status'
    ) LOOP
        EXECUTE 'ALTER TABLE orders DROP CONSTRAINT IF EXISTS ' || quote_ident(r.constraint_name);
    END LOOP;
END $$;

ALTER TABLE orders ADD CONSTRAINT chk_orders_status
    CHECK (status IN ('AWAITING_PAYMENT', 'PAID', 'DELIVERED', 'CANCELLED'));

DO $$
DECLARE
    r RECORD;
BEGIN
    FOR r IN (
        SELECT constraint_name
        FROM information_schema.constraint_column_usage
        WHERE table_name = 'order_status_history' AND column_name IN ('from_status', 'to_status', 'status')
    ) LOOP
        EXECUTE 'ALTER TABLE order_status_history DROP CONSTRAINT IF EXISTS ' || quote_ident(r.constraint_name);
    END LOOP;
END $$;

ALTER TABLE order_status_history ADD CONSTRAINT chk_order_status_history_from_status
    CHECK (from_status IS NULL OR from_status IN ('AWAITING_PAYMENT', 'PAID', 'DELIVERED', 'CANCELLED'));

ALTER TABLE order_status_history ADD CONSTRAINT chk_order_status_history_to_status
    CHECK (to_status IN ('AWAITING_PAYMENT', 'PAID', 'DELIVERED', 'CANCELLED'));

-- 6. Видавництво та рік видання (А.4)
ALTER TABLE books ADD COLUMN IF NOT EXISTS publisher VARCHAR(255) NOT NULL DEFAULT 'Невідоме видавництво';
ALTER TABLE books ADD COLUMN IF NOT EXISTS publication_year INT NOT NULL DEFAULT 2024;

ALTER TABLE books DROP CONSTRAINT IF EXISTS chk_books_publication_year;
ALTER TABLE books ADD CONSTRAINT chk_books_publication_year
    CHECK (publication_year BETWEEN 1450 AND 2100);

CREATE INDEX IF NOT EXISTS idx_books_publication_year ON books(publication_year);

-- 7. Контактна особа закладу в замовленні (А.10)
ALTER TABLE orders ADD COLUMN IF NOT EXISTS institution_contact_person VARCHAR(255);

ALTER TABLE orders DROP CONSTRAINT IF EXISTS chk_orders_gift_institution;
ALTER TABLE orders ADD CONSTRAINT chk_orders_gift_institution
    CHECK (type != 'GIFT' OR (institution_name IS NOT NULL AND institution_contact_person IS NOT NULL));

-- 8. Менеджерські фільтри замовлень та цілісність gift_log (M3, 7.2.2.6, 7.2.2.7)
CREATE INDEX IF NOT EXISTS idx_orders_unpaid_awaiting ON orders(created_at) WHERE status = 'AWAITING_PAYMENT';
CREATE INDEX IF NOT EXISTS idx_orders_archived ON orders(COALESCE(status_changed_at, created_at)) WHERE status IN ('DELIVERED', 'CANCELLED');

ALTER TABLE gift_log ALTER COLUMN order_id DROP NOT NULL;
ALTER TABLE gift_log DROP CONSTRAINT IF EXISTS gift_log_order_id_fkey;
ALTER TABLE gift_log ADD CONSTRAINT gift_log_order_id_fkey
    FOREIGN KEY (order_id) REFERENCES orders(id) ON DELETE SET NULL;
