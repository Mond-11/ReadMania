-- Читацькі виклики та фіксація їх виконання користувачами

CREATE TABLE challenges (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    required_books INT NOT NULL CHECK (required_books > 0),
    genre_id BIGINT REFERENCES genres(id) ON DELETE RESTRICT,
    deadline TIMESTAMPTZ NOT NULL,
    reward_points INT NOT NULL CHECK (reward_points >= 0),
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'COMPLETED', 'EXPIRED', 'CANCELLED')),
    finished_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_challenges_genre_id ON challenges (genre_id);
CREATE INDEX idx_challenges_status ON challenges (status);

-- Зв'язок таблиці транзакцій бонусів із викликами
ALTER TABLE bonus_transactions 
    ADD CONSTRAINT fk_bonus_transactions_challenge 
    FOREIGN KEY (challenge_id) REFERENCES challenges(id) ON DELETE SET NULL;

CREATE TABLE challenge_completions (
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    challenge_id BIGINT NOT NULL REFERENCES challenges(id) ON DELETE CASCADE,
    completed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_id, challenge_id)
);

CREATE INDEX idx_challenge_completions_challenge_id ON challenge_completions (challenge_id);
