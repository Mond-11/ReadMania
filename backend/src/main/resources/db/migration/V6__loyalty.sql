-- Програма лояльності: транзакції бонусних балів та оцінки книг

CREATE TABLE bonus_transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    points INT NOT NULL,
    type VARCHAR(50) NOT NULL CHECK (type IN ('ORDER_REWARD', 'RATING_REWARD', 'CHALLENGE_REWARD', 'SPENT', 'REFUND')),
    order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
    book_id BIGINT REFERENCES books(id) ON DELETE SET NULL,
    challenge_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_bonus_transactions_user_id ON bonus_transactions (user_id);
CREATE INDEX idx_bonus_transactions_order_id ON bonus_transactions (order_id);
CREATE INDEX idx_bonus_transactions_book_id ON bonus_transactions (book_id);
CREATE INDEX idx_bonus_transactions_challenge_id ON bonus_transactions (challenge_id);

-- Часткові унікальні індекси: запобігають повторному нарахуванню балів за те саме замовлення або виклик
CREATE UNIQUE INDEX uk_bonus_order_reward ON bonus_transactions (order_id) WHERE type = 'ORDER_REWARD';
CREATE UNIQUE INDEX uk_bonus_challenge_reward ON bonus_transactions (user_id, challenge_id) WHERE type = 'CHALLENGE_REWARD';

CREATE TABLE ratings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    order_id BIGINT REFERENCES orders(id) ON DELETE SET NULL,
    value SMALLINT NOT NULL CHECK (value BETWEEN 1 AND 5),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_ratings_user_book ON ratings (user_id, book_id) WHERE user_id IS NOT NULL;
CREATE INDEX idx_ratings_book_id ON ratings (book_id);
CREATE INDEX idx_ratings_user_id ON ratings (user_id);
CREATE INDEX idx_ratings_order_id ON ratings (order_id);
