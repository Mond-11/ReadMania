-- V3__catalog.sql
-- Жанри, автори, видання книг, зв'язки та обкладинки

CREATE TABLE genres (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_genres_lower_name ON genres (LOWER(name));

CREATE TABLE authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255) NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE UNIQUE INDEX uk_authors_lower_name ON authors (LOWER(name));
CREATE INDEX idx_authors_lower_name ON authors (LOWER(name));

CREATE TABLE books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(255) NOT NULL,
    description TEXT,
    isbn VARCHAR(20) NOT NULL,
    genre_id BIGINT NOT NULL REFERENCES genres(id) ON DELETE RESTRICT,
    price NUMERIC(12,2) NOT NULL CHECK (price >= 0),
    stock INT NOT NULL DEFAULT 0 CHECK (stock >= 0),
    deleted_at TIMESTAMPTZ,
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Частковий унікальний індекс за ISBN лише для активних (не видалених) книг
CREATE UNIQUE INDEX uk_books_isbn_active ON books (isbn) WHERE deleted_at IS NULL;

-- Індекси для пошуку, фільтрації та оптимізації FK
CREATE INDEX idx_books_lower_title ON books (LOWER(title));
CREATE INDEX idx_books_genre_id ON books (genre_id);
CREATE INDEX idx_books_price ON books (price);
CREATE INDEX idx_books_deleted_at ON books (deleted_at);

CREATE TABLE book_authors (
    book_id BIGINT NOT NULL REFERENCES books(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES authors(id) ON DELETE RESTRICT,
    PRIMARY KEY (book_id, author_id)
);

CREATE INDEX idx_book_authors_author_id ON book_authors (author_id);

CREATE TABLE book_covers (
    book_id BIGINT PRIMARY KEY REFERENCES books(id) ON DELETE CASCADE,
    content_type VARCHAR(100) NOT NULL,
    data BYTEA NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
