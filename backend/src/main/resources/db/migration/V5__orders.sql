-- Замовлення, позиції замовлень та історія змін статусів

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    type VARCHAR(50) NOT NULL CHECK (type IN ('REGULAR', 'GIFT')),
    status VARCHAR(50) NOT NULL DEFAULT 'PROCESSING' CHECK (status IN ('AWAITING_PAYMENT', 'PROCESSING', 'ASSEMBLED', 'DELIVERING', 'DELIVERED', 'CANCELLED')),
    delivery_method VARCHAR(50) CHECK (delivery_method IN ('COURIER', 'POST_OFFICE')),
    payment_method VARCHAR(50) NOT NULL CHECK (payment_method IN ('ON_DELIVERY', 'TRANSFER')),
    recipient_name VARCHAR(255),
    recipient_phone VARCHAR(50),
    delivery_address VARCHAR(500),
    institution_id BIGINT REFERENCES institutions(id) ON DELETE SET NULL,
    institution_name VARCHAR(255),
    items_total NUMERIC(12,2) NOT NULL CHECK (items_total >= 0),
    discount_amount NUMERIC(12,2) NOT NULL DEFAULT 0.00 CHECK (discount_amount >= 0),
    points_used INT NOT NULL DEFAULT 0 CHECK (points_used >= 0),
    total_to_pay NUMERIC(12,2) NOT NULL CHECK (total_to_pay >= 0),
    version BIGINT NOT NULL DEFAULT 0,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status_changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    delivered_at TIMESTAMPTZ,

    CONSTRAINT chk_orders_discount_points CHECK (discount_amount = (points_used * 10)::numeric(12,2)),
    CONSTRAINT chk_orders_total_to_pay CHECK (total_to_pay = items_total - discount_amount),
    CONSTRAINT chk_orders_max_discount CHECK (discount_amount * 10 <= items_total * 3),
    CONSTRAINT chk_orders_gift_institution CHECK (type != 'GIFT' OR institution_name IS NOT NULL)
);

CREATE INDEX idx_orders_user_created_at ON orders (user_id, created_at DESC);
CREATE INDEX idx_orders_status_created_at ON orders (status, created_at DESC);
CREATE INDEX idx_orders_institution_id ON orders (institution_id);

CREATE TABLE order_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    book_id BIGINT REFERENCES books(id) ON DELETE SET NULL,
    book_title VARCHAR(255) NOT NULL,
    book_price NUMERIC(12,2) NOT NULL CHECK (book_price >= 0),
    quantity INT NOT NULL CHECK (quantity > 0)
);

CREATE INDEX idx_order_items_order_id ON order_items (order_id);
CREATE INDEX idx_order_items_book_id ON order_items (book_id);

CREATE TABLE order_status_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    from_status VARCHAR(50),
    to_status VARCHAR(50) NOT NULL,
    changed_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    changed_by_user_id BIGINT REFERENCES users(id) ON DELETE SET NULL,
    comment VARCHAR(500)
);

CREATE INDEX idx_order_status_history_order_id ON order_status_history (order_id);
CREATE INDEX idx_order_status_history_changed_by ON order_status_history (changed_by_user_id);
