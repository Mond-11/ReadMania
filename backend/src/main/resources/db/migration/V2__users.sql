-- V2__users.sql
-- Користувачі, ролі, блокування та баланс бонусів

CREATE TABLE users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(255) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    role VARCHAR(50) NOT NULL DEFAULT 'USER' CHECK (role IN ('USER', 'MANAGER')),
    status VARCHAR(50) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'BLOCKED')),
    block_reason VARCHAR(1000),
    blocked_at TIMESTAMPTZ,
    full_name VARCHAR(255),
    phone VARCHAR(50),
    delivery_address VARCHAR(500),
    bonus_balance INT NOT NULL DEFAULT 0 CHECK (bonus_balance >= 0),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    last_login_at TIMESTAMPTZ
);

-- Унікальний email без урахування регістру
CREATE UNIQUE INDEX uk_users_lower_email ON users (LOWER(email));

-- Частковий індекс для виявлення неактивних користувачів (M5)
CREATE INDEX idx_users_m5_inactive ON users (last_login_at) WHERE status = 'ACTIVE';
