-- V8__gift_log.sql
-- Плоский журнал подарованих книг для звітності та аналітики

CREATE TABLE gift_log (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id BIGINT NOT NULL REFERENCES orders(id) ON DELETE CASCADE,
    institution_id BIGINT REFERENCES institutions(id) ON DELETE SET NULL,
    institution_name VARCHAR(255) NOT NULL,
    book_title VARCHAR(255) NOT NULL,
    quantity INT NOT NULL CHECK (quantity > 0),
    delivered_date DATE NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uk_gift_log_order_book UNIQUE (order_id, book_title)
);

CREATE INDEX idx_gift_log_institution_delivered ON gift_log (institution_id, delivered_date);
CREATE INDEX idx_gift_log_order_id ON gift_log (order_id);
